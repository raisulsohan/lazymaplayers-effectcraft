// Builds LazyMapLayers for EffectCraft into dist/ from the After Effects version next to this folder
// (../LazyMapLayers), which is never changed:
//
//   dist/host/lazymaplayers-effectcraft.jsx   host/compat.jsx + LazyMapLayers' host script + host/compat-post.jsx
//   dist/panel/                               LazyMapLayers' panel, built from its sources with this folder's
//                                             panel/cep.ts and panel/nodeFileSource.ts in place of its own,
//                                             and panel/prelude.ts in front
//   dist/data/                                LazyMapLayers' bundled data (copied from its dist/)
//
//   node tools/build.mjs [--dev] [--test]
//
// --test builds the panel with LazyMapLayers' test automation on (its in-app suites, driven by
// tools/run-suites.mjs); a normal build leaves it out.
//
// LazyMapLayers' own build must have run once (its dist/ holds the host script and the data), and its
// node_modules provide esbuild, Preact and MapLibre.

import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lml = path.resolve(root, "..", "LazyMapLayers");
const dist = path.join(root, "dist");
const dev = process.argv.includes("--dev");
const test = process.argv.includes("--test");
const target = ["chrome99"];

if (!fs.existsSync(path.join(lml, "src", "panel", "main.tsx"))) throw new Error(`LazyMapLayers sources not found at ${lml}`);
if (!fs.existsSync(path.join(lml, "dist", "host", "lazymaplayers.jsx"))) throw new Error("run LazyMapLayers' build first: cd ../LazyMapLayers && node tools/build.mjs");

const lmlRequire = createRequire(path.join(lml, "package.json"));
const esbuild = await import(pathToFileURL(lmlRequire.resolve("esbuild")).href);
const pkg = JSON.parse(fs.readFileSync(path.join(lml, "package.json"), "utf8"));

function copy(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    if (entry.isDirectory()) copyDir(path.join(from, entry.name), path.join(to, entry.name));
    else copy(path.join(from, entry.name), path.join(to, entry.name));
  }
}

/** Swaps LazyMapLayers' CEP bridge and its file source for this version's. */
const swap = {
  name: "lazymaplayers-effectcraft",
  setup(build) {
    const replacements = new Map([
      [path.join(lml, "src", "panel", "cep.ts"), path.join(root, "panel", "cep.ts")],
      [path.join(lml, "src", "panel", "basemap", "nodeFileSource.ts"), path.join(root, "panel", "nodeFileSource.ts")]
    ]);
    build.onResolve({ filter: /(cep|nodeFileSource)(\.ts)?$/ }, (args) => {
      if (!args.importer) return undefined;
      const resolved = path.resolve(args.resolveDir, args.path.endsWith(".ts") ? args.path : args.path + ".ts");
      const swapped = replacements.get(resolved);
      return swapped ? { path: swapped } : undefined;
    });
    // The host line under the panel names the app it runs in: "EffectCraft 0.8.0" out of ping's
    // "26.0 (EffectCraft 0.8.0)".
    const store = path.join(lml, "src", "panel", "store.ts");
    build.onLoad({ filter: /store\.ts$/ }, (args) => {
      if (path.resolve(args.path) !== store) return undefined;
      const text = fs.readFileSync(store, "utf8");
      const from = "`After Effects ${info.appVersion} · LazyMapLayers ${info.lml}`";
      if (!text.includes(from)) {
        console.warn("warning: the host line in src/panel/store.ts changed; it still says After Effects");
        return undefined;
      }
      return { contents: text.replace(from, "`${(/\\((EffectCraft [^)]+)\\)/.exec(info.appVersion) ?? [\"\", info.appVersion])[1]} · LazyMapLayers ${info.lml}`"), loader: "ts" };
    });
  }
};

const started = Date.now();
fs.rmSync(dist, { recursive: true, force: true });

// Host: the compatibility layer around LazyMapLayers' host script.
const host = [
  `// LazyMapLayers ${pkg.version} for EffectCraft. Generated by tools/build.mjs; edit host/ or LazyMapLayers' src/host instead.`,
  fs.readFileSync(path.join(root, "host", "compat.jsx"), "utf8"),
  fs.readFileSync(path.join(lml, "dist", "host", "lazymaplayers.jsx"), "utf8"),
  fs.readFileSync(path.join(root, "host", "compat-post.jsx"), "utf8")
].join("\n");
fs.mkdirSync(path.join(dist, "host"), { recursive: true });
fs.writeFileSync(path.join(dist, "host", "lazymaplayers-effectcraft.jsx"), host, "utf8");

// Panel.
const panelOut = path.join(dist, "panel");
const index = fs
  .readFileSync(path.join(lml, "panel", "index.html"), "utf8")
  .replace(/<title>[^<]*<\/title>/i, "<title>LazyMapLayers for EffectCraft</title>")
  .replace(/<script/i, "<!--LMLEC-->\n<script");
fs.mkdirSync(panelOut, { recursive: true });
fs.writeFileSync(path.join(panelOut, "index.html"), index, "utf8");
copy(path.join(lml, "panel", "panel.css"), path.join(panelOut, "panel.css"));
for (const name of ["icon.png", "icon@2x.png"]) copy(path.join(lml, "panel", "icons", name), path.join(panelOut, "icons", name));
copy(lmlRequire.resolve("maplibre-gl/dist/maplibre-gl.css"), path.join(panelOut, "maplibre-gl.css"));

await esbuild.build({
  entryPoints: [path.join(root, "panel", "prelude.ts")],
  outfile: path.join(panelOut, "prelude.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target,
  minify: !dev,
  logLevel: "warning"
});
await esbuild.build({
  entryPoints: [lmlRequire.resolve("maplibre-gl/dist/maplibre-gl-worker.mjs")],
  outfile: path.join(panelOut, "maplibre-worker.js"),
  bundle: true,
  format: "esm",
  target,
  minify: !dev,
  legalComments: "inline",
  logLevel: "warning"
});
await esbuild.build({
  entryPoints: [path.join(lml, "src", "panel", "render", "encodeWorker.ts")],
  outfile: path.join(panelOut, "encode-worker.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target,
  minify: !dev,
  legalComments: "inline",
  logLevel: "warning"
});
await esbuild.build({
  entryPoints: [path.join(lml, "src", "panel", "main.tsx")],
  outfile: path.join(panelOut, "panel.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target,
  jsx: "automatic",
  jsxImportSource: "preact",
  nodePaths: [path.join(lml, "node_modules")],
  sourcemap: dev ? "inline" : false,
  minify: !dev,
  legalComments: "inline",
  define: { "process.env.NODE_ENV": test ? '"development"' : '"production"' },
  plugins: [swap],
  logLevel: "warning"
});

// Data: LazyMapLayers' bundled data, as its build left it.
copyDir(path.join(lml, "dist", "data"), path.join(dist, "data"));
// The manifest only says the version (the Self-test reads it); CEP never loads this build.
copy(path.join(lml, "dist", "CSXS", "manifest.xml"), path.join(dist, "CSXS", "manifest.xml"));
copy(path.join(lml, "LICENSE"), path.join(dist, "LICENSE"));

const kb = (f) => (fs.statSync(path.join(dist, f)).size / 1024).toFixed(0) + " KB";
console.log(`built LazyMapLayers ${pkg.version} for EffectCraft${test ? " (test build)" : ""} in ${((Date.now() - started) / 1000).toFixed(1)} s: panel.js ${kb("panel/panel.js")}, host ${kb("host/lazymaplayers-effectcraft.jsx")}`);
